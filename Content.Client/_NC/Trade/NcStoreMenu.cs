[GenerateTypedNameReferences]
public sealed partial class NcStoreMenu : FancyWindow
{
    private const int SearchDebounceMs = 120;
    private const int PageSize = 96;
    private static readonly ISawmill Sawmill = Logger.GetSawmill("ncstore-ui");
    private static readonly Color CatSelected = new(0xD9, 0xA4, 0x41);
    private static readonly Color CatIdle = new(0x7C, 0x66, 0x24);

    private static readonly ISawmill Log = Logger.GetSawmill("ncstore-menu");

    private readonly Dictionary<string, (NcStoreListingControl Ctrl, string Sig)> _buyCache = new();
    private readonly Dictionary<string, Button> _buyCatButtons = new();
    private readonly List<string> _buyCats = new();
    private readonly List<StoreListingData> _items = new();

    private readonly Dictionary<string, int> _massSellTotals = new();
    private readonly IPrototypeManager _proto;

    private readonly Dictionary<string, int> _qtyCache = new();
    private readonly Dictionary<string, (NcStoreListingControl Ctrl, string Sig)> _sellCache = new();
    private readonly Dictionary<string, Button> _sellCatButtons = new();
    private readonly List<string> _sellCats = new();
    private readonly SpriteSystem _sprites;

    private int _balance;

    private string _buyCat = string.Empty;
    private int _pageBuy = 1;
    private int _pageSell = 1;

    private string _search = string.Empty;
    private int _searchToken;
    private string _sellCat = string.Empty;

    public Action<string>? OnContractClaim;

    public NcStoreMenu()
    {
        Log.Info("[NcStore/Menu] NcStoreMenu constructor START");

        RobustXamlLoader.Load(this);
        Log.Info("[NcStore/Menu] XAML loaded OK");

        IoCManager.InjectDependencies(this);
        Log.Info("[NcStore/Menu] Dependencies injected OK");

        _sprites = IoCManager.Resolve<IEntitySystemManager>().GetEntitySystem<SpriteSystem>();
        _proto = IoCManager.Resolve<IPrototypeManager>();

        SearchBar.OnTextChanged += _ =>
        {
            _search = SearchBar.Text.Trim();
            var token = ++_searchToken;

            Log.Info($"[NcStore/Menu] Search changed to '{_search}' (token={token})");

            Timer.Spawn(
                TimeSpan.FromMilliseconds(SearchDebounceMs),
                () =>
                {
                    if (token != _searchToken)
                        return;

                    Log.Info($"[NcStore/Menu] Search debounce fired for '{_search}'");
                    ResetPaging();
                    OnSearchChanged?.Invoke(_search);
                    RefreshListings();
                });
        };

        BalanceLabel.StyleClasses.Add(StyleNano.StyleClassLabelHeadingBigger);
        MassSellPulledCrateButton.Disabled = true;
        MassSellPulledCrateButton.Text = "Продать содержимое тащимого ящика";

        MassSellPulledCrateButton.OnPressed += _ =>
        {
            Log.Info("[NcStore/Menu] MassSellPulledCrateButton pressed");
            OnMassSellPulledCrate?.Invoke();
        };

        Log.Info("[NcStore/Menu] NcStoreMenu constructor END");
    }

    public event Action<string>? OnSearchChanged;
    public event Action<StoreListingData, int>? OnBuyPressed;
    public event Action<StoreListingData, int>? OnSellPressed;
    public event Action? OnMassSellPulledCrate;

    public void SetBalance(int balance)
    {
        _balance = balance;
        BalanceLabel.Text = balance.ToString();
        BalanceInfo.SetMarkup($"[font size=14][color=yellow]{balance}[/color][/font]");

        Log.Info($"[NcStore/Menu] SetBalance={balance}");
    }

    public void SetMassSellTotals(Dictionary<string, int> totals)
    {
        _massSellTotals.Clear();
        foreach (var (cur, amt) in totals)
            _massSellTotals[cur] = amt;

        if (_massSellTotals.Count == 0)
        {
            MassSellPulledCrateButton.Text = "Продать содержимое тащимого ящика";
            MassSellPulledCrateButton.Disabled = true;
            Log.Info("[NcStore/Menu] SetMassSellTotals: no currencies, button disabled");
            return;
        }

        MassSellPulledCrateButton.Disabled = false;

        var text = string.Join(", ", _massSellTotals.Select(p => $"{p.Value} {p.Key}"));
        MassSellPulledCrateButton.Text = $"Продать содержимое ({text})";

        Log.Info($"[NcStore/Menu] SetMassSellTotals: {text}");
    }

    public void ApplyState(int balance, List<StoreListingData> list, Dictionary<string, int> massTotals)
    {
        Log.Info($"[NcStore/Menu] ApplyState: balance={balance}, items={list.Count}, massTotals={massTotals.Count}");
        SetBalance(balance);
        SetMassSellTotals(massTotals);
        Populate(list);
    }

    public void Populate(List<StoreListingData> list)
    {
        Log.Info($"[NcStore/Menu] Populate() with {list.Count} items");

        _items.Clear();
        _items.AddRange(list);

        var ids = _items.Select(i => i.Id).ToHashSet();
        foreach (var key in _qtyCache.Keys.Where(k => !ids.Contains(k)).ToList())
            _qtyCache.Remove(key);

        _buyCats.Clear();
        _sellCats.Clear();

        _buyCats.AddRange(
            list.Where(i => i.Mode == StoreMode.Buy)
                .Select(i => i.Category)
                .Distinct()
                .OrderBy(c => c));

        _sellCats.AddRange(
            list.Where(i => i.Mode == StoreMode.Sell)
                .Select(i => i.Category)
                .Distinct()
                .OrderBy(c => c));

        Sawmill.Info(
            $"[NcStore/UI] Items={list.Count}, BuyCats={list.Count(i => i.Mode == StoreMode.Buy)}, SellCats={list.Count(i => i.Mode == StoreMode.Sell)}");
        const string readyCat = "Готово к продаже";
        if (_items.Any(i => i.Mode == StoreMode.Sell && i.Category == readyCat))
        {
            _sellCats.Remove(readyCat);
            _sellCats.Insert(0, readyCat);
            if (string.IsNullOrEmpty(_sellCat))
                _sellCat = readyCat;
        }

        if (!_buyCats.Contains(_buyCat))
            _buyCat = string.Empty;
        if (!_sellCats.Contains(_sellCat))
            _sellCat = string.Empty;

        Log.Info(
            $"[NcStore/Menu] Cats: buy={_buyCats.Count}, sell={_sellCats.Count}, " +
            $"buySelected='{_buyCat}', sellSelected='{_sellCat}'");

        BuildCategoryButtons();
        ResetPaging();
        RefreshListings();
    }

    private void RefreshListings()
    {
        var hasSearch = !string.IsNullOrWhiteSpace(_search);
        var buyCount = Filtered(StoreMode.Buy, _buyCat).Count();
        var sellCount = Filtered(StoreMode.Sell, _sellCat).Count();

        Log.Info(
            $"[NcStore/Menu] RefreshListings: search='{_search}', buyCat='{_buyCat}', sellCat='{_sellCat}', " +
            $"buyCount={buyCount}, sellCount={sellCount}");

        BuyCategoryHeader.Visible = !string.IsNullOrEmpty(_buyCat) || hasSearch;
        SellCategoryHeader.Visible = !string.IsNullOrEmpty(_sellCat) || hasSearch;

        if (BuyCategoryHeader.Visible)
        {
            BuyCategoryHeader.Text = !string.IsNullOrEmpty(_buyCat)
                ? _buyCat
                : $"Результаты поиска ({buyCount})";
        }
        else
            BuyCategoryHeader.Text = string.Empty;

        if (SellCategoryHeader.Visible)
        {
            SellCategoryHeader.Text = !string.IsNullOrEmpty(_sellCat)
                ? _sellCat
                : $"Результаты поиска ({sellCount})";
        }
        else
            SellCategoryHeader.Text = string.Empty;

        FillPaneFull(BuyListingsContainer, StoreMode.Buy, _buyCat, (d, qty) => OnBuyPressed?.Invoke(d, qty));
        FillPaneFull(SellListingsContainer, StoreMode.Sell, _sellCat, (d, qty) => OnSellPressed?.Invoke(d, qty));
    }

    private IEnumerable<StoreListingData> Filtered(StoreMode mode, string cat)
    {
        var q = _items.Where(i => i.Mode == mode);

        var hasCat = !string.IsNullOrEmpty(cat);
        var hasSearch = !string.IsNullOrWhiteSpace(_search);
        if (!hasCat && !hasSearch)
            return Enumerable.Empty<StoreListingData>();
        if (hasCat)
            q = q.Where(i => i.Category == cat);

        if (hasSearch)
            q = q.Where(i => MatchesSearch(i.ProductEntity));

        return q;
    }

    private void FillPaneFull(Control pane, StoreMode mode, string cat, Action<StoreListingData, int> emit)
    {
        pane.Children.Clear();

        var filtered = Filtered(mode, cat).ToList();

        if (string.IsNullOrEmpty(cat) && string.IsNullOrWhiteSpace(_search))
        {
            Log.Info($"[NcStore/Menu] FillPaneFull({mode}): no cat and no search, nothing to show");
            return;
        }

        if (filtered.Count == 0)
        {
            Log.Info($"[NcStore/Menu] FillPaneFull({mode}): filtered empty");
            pane.AddChild(new Label { Text = "Выберите категорию.", });
            return;
        }

        var take = Math.Min(filtered.Count, PageSize * (mode == StoreMode.Buy ? _pageBuy : _pageSell));
        var slice = filtered.GetRange(0, take);

        Log.Info(
            $"[NcStore/Menu] FillPaneFull({mode}): total={filtered.Count}, showing={slice.Count}, pageBuy={_pageBuy}, pageSell={_pageSell}");

        AddListingRange(pane, mode, filtered, 0, slice.Count, emit);
        AddOrUpdateMoreButton(pane, mode, filtered.Count, take, cat, emit);
    }

    private void AppendNextPage(Control pane, StoreMode mode, string cat, Action<StoreListingData, int> emit)
    {
        var filtered = Filtered(mode, cat).ToList();
        var page = mode == StoreMode.Buy ? _pageBuy : _pageSell;
        var take = Math.Min(filtered.Count, PageSize * page);

        var already = 0;
        foreach (var ch in pane.Children)
            if (ch is NcStoreListingControl)
                already++;

        var toAddStart = already;
        var toAddEnd = Math.Min(take, filtered.Count);

        Log.Info(
            $"[NcStore/Menu] AppendNextPage({mode}): total={filtered.Count}, page={page}, already={already}, add={toAddEnd - toAddStart}");

        if (toAddStart < toAddEnd)
            AddListingRange(pane, mode, filtered, toAddStart, toAddEnd, emit);

        RemoveMoreButtons(pane);
        AddOrUpdateMoreButton(pane, mode, filtered.Count, take, cat, emit);
    }

    private void AddListingRange(
        Control pane,
        StoreMode mode,
        List<StoreListingData> source,
        int startExclusive,
        int endExclusive,
        Action<StoreListingData, int> emit
    )
    {
        var cache = mode == StoreMode.Buy ? _buyCache : _sellCache;

        Log.Info($"[NcStore/Menu] AddListingRange({mode}): from={startExclusive} to={endExclusive}");

        for (var i = startExclusive; i < endExclusive; i++)
        {
            var it = source[i];
            var sig = Sig(it, _balance);

            NcStoreListingControl ctrl;
            if (cache.TryGetValue(it.Id, out var tuple) && tuple.Sig == sig)
                ctrl = tuple.Ctrl;
            else
            {
                var initQty = _qtyCache.TryGetValue(it.Id, out var saved) ? saved : 1;
                Log.Info(
                    $"[NcStore/Menu] Creating listing control id={it.Id}, mode={it.Mode}, price={it.Price}, remaining={it.Remaining}, owned={it.Owned}, initQty={initQty}");
                ctrl = new(it, _sprites, _balance, initQty);
                ctrl.OnQtyChanged += newQty => _qtyCache[it.Id] = newQty;

                switch (mode)
                {
                    case StoreMode.Buy:
                        ctrl.OnBuyPressed += qty => emit(it, qty);
                        break;
                    case StoreMode.Sell:
                        ctrl.OnSellPressed += qty => emit(it, qty);
                        break;
                }

                cache[it.Id] = (ctrl, sig);
            }

            pane.AddChild(ctrl);

            if (i < endExclusive - 1)
            {
                pane.AddChild(
                    new PanelContainer
                    {
                        MinSize = new Vector2i(0, 1),
                        StyleClasses = { "LowDivider", }
                    });
            }
        }
    }

    private static void RemoveMoreButtons(Control pane)
    {
        foreach (var ch in pane.Children.ToList())
            if (ch is Button b && b.Text != null && b.Text.StartsWith("Показать ещё (", StringComparison.Ordinal))
                pane.RemoveChild(b);
    }

    private void AddOrUpdateMoreButton(
        Control pane,
        StoreMode mode,
        int totalCount,
        int shown,
        string cat,
        Action<StoreListingData, int> emit
    )
    {
        if (shown >= totalCount)
        {
            Log.Info($"[NcStore/Menu] AddOrUpdateMoreButton({mode}): all shown ({shown}/{totalCount})");
            return;
        }

        var left = totalCount - shown;

        var more = new Button
        {
            Text = $"Показать ещё ({left})",
            HorizontalExpand = true,
            Margin = new(0, 8, 0, 8)
        };

        more.OnPressed += _ =>
        {
            if (mode == StoreMode.Buy)
                _pageBuy++;
            else
                _pageSell++;

            Log.Info($"[NcStore/Menu] More pressed for {mode}, new pageBuy={_pageBuy}, pageSell={_pageSell}");
            AppendNextPage(pane, mode, cat, emit);
        };

        pane.AddChild(more);
    }

    private void BuildCategoryButtons()
    {
        _buyCatButtons.Clear();
        _sellCatButtons.Clear();

        MakeButtons(
            _buyCats,
            BuyCategoryListContainer,
            _buyCat,
            _buyCatButtons,
            cat =>
            {
                _buyCat = _buyCat == cat ? string.Empty : cat;
                Log.Info($"[NcStore/Menu] Buy category clicked: '{cat}', now selected='{_buyCat}'");
                UpdateCatVisuals(_buyCatButtons, _buyCat);
                ResetPaging();
                RefreshListings();
            });

        MakeButtons(
            _sellCats,
            SellCategoryListContainer,
            _sellCat,
            _sellCatButtons,
            cat =>
            {
                _sellCat = _sellCat == cat ? string.Empty : cat;
                Log.Info($"[NcStore/Menu] Sell category clicked: '{cat}', now selected='{_sellCat}'");
                UpdateCatVisuals(_sellCatButtons, _sellCat);
                ResetPaging();
                RefreshListings();
            });

        UpdateCatVisuals(_buyCatButtons, _buyCat);
        UpdateCatVisuals(_sellCatButtons, _sellCat);
    }

    private static void MakeButtons(
        IEnumerable<string> cats,
        Control parent,
        string current,
        Dictionary<string, Button> registry,
        Action<string> onClick
    )
    {
        parent.Children.Clear();

        foreach (var c in cats)
        {
            var catId = c;

            var display = c;
            if (c == "Готово к продаже")
                display = "Готово";
            else if (c == "Готово к продаже в ящике")
                display = "В ящике";

            var selected = catId == current;

            var btn = new Button
            {
                Text = display,
                ToggleMode = true,
                HorizontalExpand = true,
                Pressed = selected,
                ModulateSelfOverride = selected ? CatSelected : CatIdle,
                ToolTip = c
            };

            btn.OnMouseEntered += _ =>
                btn.ModulateSelfOverride = btn.Pressed ? Brighten(CatSelected, 1.2f) : Brighten(CatIdle, 1.2f);
            btn.OnMouseExited += _ =>
                btn.ModulateSelfOverride = btn.Pressed ? CatSelected : CatIdle;

            btn.OnPressed += _ => onClick(catId);

            parent.AddChild(btn);
            registry[catId] = btn;
        }
    }

    public void PopulateContracts(List<ContractClientData> list)
    {
        Log.Info($"[NcStore/Menu] PopulateContracts() count={list.Count}");

        if (ContractList == null)
        {
            Log.Warning("[NcStore/Menu] PopulateContracts: ContractList is null");
            return;
        }

        ContractList.RemoveAllChildren();

        var ordered = list
            .OrderBy(x => x.Difficulty switch
            {
                "Easy" => 0,
                "Medium" => 1,
                "Hard" => 2,
                _ => 99
            })
            .ThenBy(x => x.Completed ? 1 : 0)
            .ToList();

        foreach (var c in ordered)
        {
            var panel = new PanelContainer
            {
                StyleClasses = { "NcContractPanel", },
                Margin = new(0, 0, 0, 8)
            };

            var box = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                Margin = new(8, 8, 8, 8),
                HorizontalExpand = true
            };

            var titleText = string.IsNullOrWhiteSpace(c.Name)
                ? $"★ {DifficultyName(c.Difficulty)} контракт"
                : $"★ {c.Name} ({DifficultyName(c.Difficulty)})";

            box.AddChild(
                new Label
                {
                    Text = titleText,
                    StyleClasses = { "NcContractTitle", }
                });


            if (!string.IsNullOrWhiteSpace(c.Description))
            {
                box.AddChild(
                    new Label
                    {
                        Text = c.Description,
                        StyleClasses = { "NcContractDescription", },
                        Margin = new(0, 2, 0, 2)
                    });
            }

            // Цель контракта: иконка + красивое имя + описание
            EntityPrototype? targetProto = null;
            if (!string.IsNullOrWhiteSpace(c.TargetItem))
                _proto.TryIndex(c.TargetItem, out targetProto);

            var targetRow = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                Margin = new(0, 2, 0, 2)
            };

            // Иконка предмета цели
            Texture? targetTex = null;
            if (targetProto != null)
            {
                var icon = _sprites.GetPrototypeIcon(targetProto.ID);
                targetTex = icon.Default;
            }

            if (targetTex != null)
            {
                targetRow.AddChild(
                    new TextureRect
                    {
                        Texture = targetTex,
                        Stretch = TextureRect.StretchMode.KeepAspectCentered,
                        MinSize = new(24, 24),
                        Margin = new(0, 0, 4, 0)
                    });
            }

            var targetName = targetProto?.Name ?? c.TargetItem;

            targetRow.AddChild(
                new Label
                {
                    Text = $"Цель: {targetName}"
                });

            box.AddChild(targetRow);

            // Описание предмета, если есть
            if (!string.IsNullOrWhiteSpace(targetProto?.Description))
            {
                box.AddChild(
                    new Label
                    {
                        Text = targetProto.Description,
                        StyleClasses = { "NcContractItemDescription", },
                        Margin = new(0, 0, 0, 2)
                    });
            }


            if (!c.Completed)
            {
                box.AddChild(
                    new Label
                    {
                        Text = $"Прогресс: {c.Progress} / {c.Required}",
                        StyleClasses = { "NcContractProgress", }
                    });
            }
            else
            {
                box.AddChild(
                    new Label
                    {
                        Text = "✔ Выполнено",
                        StyleClasses = { "NcContractDone", }
                    });
            }

            var rewardRow = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                Margin = new(0, 4, 0, 0)
            };

            Texture? currencyTex = null;

            if (!string.IsNullOrEmpty(c.RewardCurrency) &&
                _proto.TryIndex<StackPrototype>(c.RewardCurrency, out var stackProto) &&
                _proto.TryIndex<EntityPrototype>(stackProto.Spawn, out var currencyEnt))
            {
                var icon = _sprites.GetPrototypeIcon(currencyEnt.ID);
                currencyTex = icon.Default;
            }

            if (currencyTex != null)
            {
                rewardRow.AddChild(
                    new TextureRect
                    {
                        Texture = currencyTex,
                        Stretch = TextureRect.StretchMode.KeepAspectCentered,
                        MinSize = new(16, 16),
                        Margin = new(0, 0, 4, 0)
                    });
            }

            rewardRow.AddChild(
                new Label
                {
                    Text = $"Награда: {c.Reward} {c.RewardCurrency}"
                });

            box.AddChild(rewardRow);

            if (!string.IsNullOrWhiteSpace(c.RewardItem) && c.RewardItemCount > 0)
            {
                EntityPrototype? rewardProto = null;
                _proto.TryIndex(c.RewardItem, out rewardProto);

                var rewardItemRow = new BoxContainer
                {
                    Orientation = BoxContainer.LayoutOrientation.Horizontal,
                    Margin = new(0, 2, 0, 0)
                };

                Texture? rewardTex = null;
                if (rewardProto != null)
                {
                    var icon = _sprites.GetPrototypeIcon(rewardProto.ID);
                    rewardTex = icon.Default;
                }

                if (rewardTex != null)
                {
                    rewardItemRow.AddChild(
                        new TextureRect
                        {
                            Texture = rewardTex,
                            Stretch = TextureRect.StretchMode.KeepAspectCentered,
                            MinSize = new(20, 20),
                            Margin = new(0, 0, 4, 0)
                        });
                }

                var rewardName = rewardProto?.Name ?? c.RewardItem;

                rewardItemRow.AddChild(
                    new Label
                    {
                        Text = $"Предмет: {rewardName} ×{c.RewardItemCount}"
                    });

                box.AddChild(rewardItemRow);
            }

            var btn = new Button
            {
                Text = c.Completed ? "Забрать награду" : "Сдать",
                HorizontalExpand = true,
                Margin = new(0, 6, 0, 0)
            };

            btn.OnPressed += _ =>
            {
                Log.Info($"[NcStore/Menu] Contract button pressed id={c.Id}, completed={c.Completed}");
                OnContractClaim?.Invoke(c.Id);
            };
            box.AddChild(btn);

            panel.AddChild(box);
            ContractList.AddChild(panel);
        }
    }

    private string DifficultyName(string diff) =>
        diff switch
        {
            "Easy" => "Лёгкий",
            "Medium" => "Средний",
            "Hard" => "Тяжёлый",
            _ => diff
        };

    private static void UpdateCatVisuals(Dictionary<string, Button> map, string current)
    {
        foreach (var (name, btn) in map)
        {
            var selected = name == current;
            btn.Pressed = selected;
            btn.ModulateSelfOverride = selected ? CatSelected : CatIdle;
        }
    }

    private static Color Brighten(Color c, float f) =>
        new(MathF.Min(c.R * f, 1f), MathF.Min(c.G * f, 1f), MathF.Min(c.B * f, 1f), c.A);

    private void ResetPaging()
    {
        _pageBuy = 1;
        _pageSell = 1;
        Log.Info("[NcStore/Menu] ResetPaging()");
    }

    private static string Sig(StoreListingData d, int balance) =>
        d.Mode == StoreMode.Buy
            ? $"{d.Price}|{d.Remaining}|{d.Owned}|{d.CurrencyId}|{d.ProductEntity}|B{balance}"
            : $"{d.Price}|{d.Remaining}|{d.Owned}|{d.CurrencyId}|{d.ProductEntity}";

    private bool MatchesSearch(string protoId)
    {
        if (string.IsNullOrWhiteSpace(_search))
            return true;

        if (!_proto.TryIndex<EntityPrototype>(protoId, out var p))
            return false;

        return p.Name.Contains(_search, StringComparison.OrdinalIgnoreCase)
            || !string.IsNullOrEmpty(p.Description)
            && p.Description.Contains(_search, StringComparison.OrdinalIgnoreCase);
    }
}
