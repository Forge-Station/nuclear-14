                {
                    Orientation = BoxContainer.LayoutOrientation.Horizontal,
                    Margin = new(0, 0, 0, 2)
                };

                Texture? targetTex = null;
                if (targetProto != null)
                {
                    var icon = _sprites.GetPrototypeIcon(targetProto.ID);
                    targetTex = icon.Default;
