                    BackgroundColor = new(0.06f, 0.06f, 0.07f, 0.98f),
                    BorderColor = borderColor,
                    BorderThickness = new(2),
                    ContentMarginLeftOverride = 8,
                    ContentMarginRightOverride = 8,
