                    {
                        Text = targetProto.Description,
                        Margin = new(0, 0, 0, 4)
                    };
                    itemDesc.StyleClasses.Add("LabelSubText");
                    root.AddChild(itemDesc);
                }
            }

            // --- Прогресс ---
            if (!c.Completed)
            {
                var max = c.Required <= 0 ? 1 : c.Required;
                var val = Math.Clamp(c.Progress, 0, max);

                root.AddChild(
                    new Label
                    {
                        Text = Loc.GetString(
                            "nc-store-contract-progress-line",
