                { Text = Loc.GetString("nc-store-contract-reward-header"), Margin = new(0, 0, 0, 3), };
            rewardsHeader.StyleClasses.Add("LabelHeading");
            rewardsCol.AddChild(rewardsHeader);

            if (c.RewardCurrencies is { Count: > 0, } currencies)
            {
                var parts = new List<string>();
                foreach (var kv in currencies)
                {
                    var curId = kv.Key;
                    var amount = kv.Value;
                    if (amount <= 0 || string.IsNullOrWhiteSpace(curId))
                        continue;

                    var name = CurrencyName(curId);
                    if (string.IsNullOrWhiteSpace(name))
                        name = curId;

                    parts.Add($"{amount} {name}");
                }

                if (parts.Count > 0)
                {
                    var curLine = new Label { Text = string.Join(", ", parts), };
                    curLine.StyleClasses.Add("LabelSubText");
                    rewardsCol.AddChild(curLine);
                }
            }
            else if (c.Reward > 0 && !string.IsNullOrWhiteSpace(c.RewardCurrency))
            {
                Texture? currencyTex = null;
                if (_proto.TryIndex<StackPrototype>(c.RewardCurrency, out var stackProto) &&
                    _proto.TryIndex<EntityPrototype>(stackProto.Spawn, out var currencyEnt))
                {
                    var icon = _sprites.GetPrototypeIcon(currencyEnt.ID);
                    currencyTex = icon.Default;
                }

                var line = new BoxContainer
                {
                    Orientation = BoxContainer.LayoutOrientation.Horizontal,
                    Margin = new(0, 0, 0, 2)
                };

                if (currencyTex != null)
                {
                    line.AddChild(
                        new TextureRect
                        {
                            Texture = currencyTex,
                            Stretch = TextureRect.StretchMode.KeepAspectCentered,
                            MinSize = new(16, 16),
                            Margin = new(0, 0, 4, 0)
                        });
                }

                var currencyName = CurrencyName(c.RewardCurrency);
                var curText = string.IsNullOrEmpty(currencyName)
                    ? $"{c.Reward}"
                    : $"{c.Reward} {currencyName}";

                var curLine = new Label { Text = curText, };
                curLine.StyleClasses.Add("LabelSubText");

                line.AddChild(curLine);
                rewardsCol.AddChild(line);
            }

            var anyItems = c.RewardItems is { Count: > 0, } ||
                !string.IsNullOrWhiteSpace(c.RewardItem) && c.RewardItemCount > 0;

            if (anyItems)
            {
                rewardsCol.AddChild(new() { MinSize = new(0, 4), });

                var itemsHeader = new Label
                    { Text = Loc.GetString("nc-store-contract-items-header"), Margin = new(0, 2, 0, 2), };
                itemsHeader.StyleClasses.Add("LabelHeading");
                rewardsCol.AddChild(itemsHeader);
            }

            if (c.RewardItems is { Count: > 0, } items)
            {
                foreach (var kv in items)
                {
                    var id = kv.Key;
                    var count = kv.Value;
                    if (count <= 0 || string.IsNullOrWhiteSpace(id))
                        continue;

                    _proto.TryIndex<EntityPrototype>(id, out var proto);

                    var line = new BoxContainer
                    {
                        Orientation = BoxContainer.LayoutOrientation.Horizontal,
                        Margin = new(0, 0, 0, 2)
                    };

                    Texture? tex = null;
                    if (proto != null)
                    {
                        var icon = _sprites.GetPrototypeIcon(proto.ID);
                        tex = icon.Default;
                    }

                    if (tex != null)
                    {
                        line.AddChild(
                            new TextureRect
                            {
                                Texture = tex,
                                Stretch = TextureRect.StretchMode.KeepAspectCentered,
                                MinSize = new(20, 20),
                                Margin = new(0, 0, 4, 0)
                            });
                    }

                    var name = proto?.Name ?? id;
                    line.AddChild(
                        new Label
                        {
                            Text = Loc.GetString("nc-store-contract-goal-line", ("item", name), ("count", count))
                        });

                    rewardsCol.AddChild(line);
                }
            }
            else if (!string.IsNullOrWhiteSpace(c.RewardItem) && c.RewardItemCount > 0)
            {
                _proto.TryIndex<EntityPrototype>(c.RewardItem, out var rewardProto);

                var line = new BoxContainer
                {
                    Orientation = BoxContainer.LayoutOrientation.Horizontal,
                    Margin = new(0, 0, 0, 2)
                };

                Texture? rewardTex = null;
                if (rewardProto != null)
                {
                    var icon = _sprites.GetPrototypeIcon(rewardProto.ID);
                    rewardTex = icon.Default;
                }

                if (rewardTex != null)
                {
                    line.AddChild(
                        new TextureRect
                        {
                            Texture = rewardTex,
                            Stretch = TextureRect.StretchMode.KeepAspectCentered,
                            MinSize = new(20, 20),
                            Margin = new(0, 0, 4, 0)
                        });
                }

                var rewardName = rewardProto?.Name ?? c.RewardItem;
                line.AddChild(
                    new Label
                    {
                        Text = Loc.GetString(
                            "nc-store-contract-goal-line",
                            ("item", rewardName),
                            ("count", c.RewardItemCount))
                    });

                rewardsCol.AddChild(line);
            }

            bottomWrap.AddChild(rewardsPanel);
            var actionCol = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                MinSize = new(180, 0),
                Margin = new(8, 0, 0, 0)
            };

            var actionHint = new Label
            {
                Text = c.Completed
                    ? Loc.GetString("nc-store-contract-action-can-claim")
                    : Loc.GetString("nc-store-contract-action-not-done"),
                Margin = new(0, 0, 0, 4)
            };
            actionHint.StyleClasses.Add("LabelSubText");
            actionCol.AddChild(actionHint);

            actionCol.AddChild(new() { VerticalExpand = true, });

            var canClaim = c.Completed;

            var btn = new Button
            {
                Text = canClaim
                    ? Loc.GetString("nc-store-contract-action-claim")
                    : Loc.GetString(
                        "nc-store-contract-action-claim-progress",
                        ("progress", c.Progress),
                        ("required", c.Required)),
                Disabled = !canClaim,
                HorizontalExpand = true,
                MinSize = new(0, 32)
            };

            btn.ToolTip = canClaim
                ? !c.Repeatable
                    ? Loc.GetString("nc-store-contract-claim-tooltip-single")
                    : Loc.GetString("nc-store-contract-claim-tooltip-repeatable")
                : Loc.GetString("nc-store-contract-claim-tooltip-not-done");

            btn.OnPressed += _ =>
            {
                if (!canClaim)
                    return;

                OnContractClaim?.Invoke(c.Id);
            };

            actionCol.AddChild(btn);
            bottomWrap.AddChild(actionCol);

            root.AddChild(bottomWrap);

            contractList.AddChild(cardRow);
        }

        ApplyTabsVisibility();
    }


    private void RefreshListings()
    {
        var hasSearch = !string.IsNullOrWhiteSpace(_search);
        var buyFiltered = Filtered(StoreMode.Buy, _buyCat).ToList();
        var sellFiltered = Filtered(StoreMode.Sell, _sellCat).ToList();

        var buyCount = buyFiltered.Count;
        var sellCount = sellFiltered.Count;

        BuyCategoryHeader.Visible = !string.IsNullOrEmpty(_buyCat) || hasSearch;
        SellCategoryHeader.Visible = !string.IsNullOrEmpty(_sellCat) || hasSearch;

        if (BuyCategoryHeader.Visible)
        {
            BuyCategoryHeader.Text = !string.IsNullOrEmpty(_buyCat)
                ? GetCategoryDisplayName(_buyCat)
                : Loc.GetString("nc-store-search-results-buy", ("count", buyCount));
        }
        else
            BuyCategoryHeader.Text = string.Empty;

        if (SellCategoryHeader.Visible)
        {
            SellCategoryHeader.Text = !string.IsNullOrEmpty(_sellCat)
                ? GetCategoryDisplayName(_sellCat)
                : Loc.GetString("nc-store-search-results-sell", ("count", sellCount));
        }
        else
            SellCategoryHeader.Text = string.Empty;

        var buyEmit = new Action<StoreListingData, int>((d, qty) => OnBuyPressed?.Invoke(d, qty));
        if (!TryUpdatePaneInPlace(BuyListingsContainer, StoreMode.Buy, _buyCat, buyFiltered, buyEmit))
        {
            FillPaneFull(
                BuyListingsContainer,
                StoreMode.Buy,
                _buyCat,
                buyFiltered,
                buyEmit);
        }

        var sellEmit = new Action<StoreListingData, int>((d, qty) => OnSellPressed?.Invoke(d, qty));
        if (!TryUpdatePaneInPlace(SellListingsContainer, StoreMode.Sell, _sellCat, sellFiltered, sellEmit))
        {
            FillPaneFull(
                SellListingsContainer,
                StoreMode.Sell,
                _sellCat,
                sellFiltered,
                sellEmit);
        }
    }

    private bool TryUpdatePaneInPlace(
        Control pane,
        StoreMode mode,
        string cat,
        List<StoreListingData> filtered,
        Action<StoreListingData, int> emit
    )
    {
        if (pane.Children.Any(c => c is Label))
            return false;

        var page = mode == StoreMode.Buy ? _pageBuy : _pageSell;
        var take = Math.Min(filtered.Count, PageSize * page);

        if (take <= 0)
            return false;

        var ctrls = pane.Children.OfType<NcStoreListingControl>().ToArray();

        if (ctrls.Length != take)
            return false;

        for (var i = 0; i < take; i++)
        {
            var it = filtered[i];
            var ctrl = ctrls[i];

            if (!string.Equals(ctrl.ListingId, it.Id, StringComparison.Ordinal))
                ctrl.UpdateIdentity(it);

            var balanceHint = mode == StoreMode.Buy
                ? GetBalanceForCurrency(it.CurrencyId)
                : int.MaxValue;

            var captured = it;
            ctrl.OnBuyPressed = mode == StoreMode.Buy ? qty => emit(captured, qty) : null;
            ctrl.OnSellPressed = mode == StoreMode.Sell ? qty => emit(captured, qty) : null;

            ctrl.UpdateDynamicData(balanceHint, it.Remaining, it.Owned);
        }

        RemoveMoreButtons(pane);
        AddOrUpdateMoreButton(pane, mode, filtered.Count, take, cat, emit);

        return true;
    }


    private IEnumerable<StoreListingData> Filtered(StoreMode mode, string cat)
    {
        var q = _items.Where(i => i.Mode == mode);

        var hasCat = !string.IsNullOrEmpty(cat);
        var hasSearch = !string.IsNullOrWhiteSpace(_searchLower);

        if (!hasCat && !hasSearch)
            return Enumerable.Empty<StoreListingData>();

        if (hasCat)
            q = q.Where(i => i.Category == cat);

        if (hasSearch)
            q = q.Where(i => MatchesSearch(i.ProductEntity));

        return q;
    }

    private void FillPaneFull(
        Control pane,
        StoreMode mode,
        string cat,
        List<StoreListingData> filtered,
        Action<StoreListingData, int> emit
    )
    {
        pane.Children.Clear();

        var hasCat = !string.IsNullOrEmpty(cat);
        var hasSearch = !string.IsNullOrWhiteSpace(_searchLower);

        if (!hasCat && !hasSearch)
        {
            pane.AddChild(new Label { Text = Loc.GetString("nc-store-select-category"), });
            return;
        }

        if (filtered.Count == 0)
        {
            var message = Loc.GetString(
                !string.IsNullOrEmpty(cat) ? "nc-store-empty-category-search" : "nc-store-empty-search");

            pane.AddChild(new Label { Text = message, });
            return;
        }

        var page = mode == StoreMode.Buy ? _pageBuy : _pageSell;
        var take = Math.Min(filtered.Count, PageSize * page);

        AddListingRange(pane, mode, filtered, 0, take, emit);

        AddOrUpdateMoreButton(pane, mode, filtered.Count, take, cat, emit);
    }


    private void AppendNextPage(Control pane, StoreMode mode, string cat, Action<StoreListingData, int> emit)
    {
        var filtered = Filtered(mode, cat).ToList();
        var page = mode == StoreMode.Buy ? _pageBuy : _pageSell;
        var take = Math.Min(filtered.Count, PageSize * page);

        var already = 0;
        foreach (var ch in pane.Children)
            if (ch is NcStoreListingControl)
                already++;

        var toAddStart = already;
        var toAddEnd = Math.Min(take, filtered.Count);

        if (toAddStart < toAddEnd)
            AddListingRange(pane, mode, filtered, toAddStart, toAddEnd, emit);

        RemoveMoreButtons(pane);
        AddOrUpdateMoreButton(pane, mode, filtered.Count, take, cat, emit);
    }

    private void AddListingRange(
        Control pane,
        StoreMode mode,
        List<StoreListingData> source,
        int startExclusive,
        int endExclusive,
        Action<StoreListingData, int> emit
    )
    {
        var cache = mode == StoreMode.Buy ? _buyCache : _sellCache;

        for (var i = startExclusive; i < endExclusive; i++)
        {
            var it = source[i];

            var balanceHint = mode == StoreMode.Buy
                ? GetBalanceForCurrency(it.CurrencyId)
                : int.MaxValue;

            var sig = Sig(it);

            if (!cache.TryGetValue(it.Id, out var tuple) || tuple.Sig != sig)
            {
                var initQty = _qtyCache.GetValueOrDefault(it.Id, 1);
                var actionsEnabled = true;

                var created = new NcStoreListingControl(it, _sprites, balanceHint, initQty, actionsEnabled);
                created.OnQtyChanged = newQty => _qtyCache[it.Id] = newQty;

                cache[it.Id] = (created, sig);
                tuple = (created, sig);
            }

            var ctrl = tuple.Ctrl;
            ctrl.OnBuyPressed = mode == StoreMode.Buy ? qty => emit(it, qty) : null;
            ctrl.OnSellPressed = mode == StoreMode.Sell ? qty => emit(it, qty) : null;

            ctrl.UpdateDynamicData(balanceHint, it.Remaining, it.Owned);

            pane.AddChild(ctrl);

            if (i < endExclusive - 1)
            {
                pane.AddChild(
                    new PanelContainer
                    {
                        MinSize = new Vector2i(0, 1),
                        StyleClasses = { "LowDivider", }
                    });
            }
        }
    }


    private static void RemoveMoreButtons(Control pane)
    {
        foreach (var ch in pane.Children.ToList())
        {
            if (ch is not Button b)
                continue;

            if (b.Name == "MoreButton")
                pane.RemoveChild(b);
        }
    }

    private void AddOrUpdateMoreButton(
        Control pane,
        StoreMode mode,
        int totalCount,
        int shown,
        string cat,
        Action<StoreListingData, int> emit
    )
    {
        if (shown >= totalCount)
            return;

        var left = totalCount - shown;

        var more = new Button
        {
            Name = "MoreButton",
            Text = Loc.GetString("nc-store-show-more", ("count", left)),
            HorizontalExpand = true,
            Margin = new(0, 8, 0, 8)
        };

        more.OnPressed += _ =>
        {
            if (mode == StoreMode.Buy)
                _pageBuy++;
            else
                _pageSell++;

            AppendNextPage(pane, mode, cat, emit);
        };

        pane.AddChild(more);
    }

    private void BuildCategoryButtons()
    {
        SyncCategoryButtons(
            _buyCats,
            BuyCategoryListContainer,
            _buyCatButtons,
            _buyCat,
            cat =>
            {
                _buyCat = _buyCat == cat ? string.Empty : cat;
                UpdateCatVisuals(_buyCatButtons, _buyCat);

                ResetPaging();
                RefreshListings();
            });

        SyncCategoryButtons(
            _sellCats,
            SellCategoryListContainer,
            _sellCatButtons,
            _sellCat,
            cat =>
            {
                _sellCat = _sellCat == cat ? string.Empty : cat;

                UpdateCatVisuals(_sellCatButtons, _sellCat);

                ResetPaging();
                RefreshListings();
            });
    }

    private Button CreateCategoryButton(string catId, Action<string> onClick)
    {
        var btn = new Button
        {
            Text = GetCategoryDisplayName(catId),
            ToggleMode = true,
            HorizontalExpand = true,
            ToolTip = GetCategoryToolTip(catId),
            ModulateSelfOverride = CatIdle
        };

        btn.OnPressed += _ => onClick(catId);
        btn.OnMouseEntered += _ =>
        {
            btn.ModulateSelfOverride = btn.Pressed
                ? Brighten(CatSelected, 1.2f)
                : Brighten(CatIdle, 1.2f);
        };

        btn.OnMouseExited += _ => { btn.ModulateSelfOverride = btn.Pressed ? CatSelected : CatIdle; };

        return btn;
    }

    private void SyncCategoryButtons(
        List<string> neededCats,
        Control parent,
        Dictionary<string, Button> registry,
        string selectedCat,
        Action<string> onClick
    )
    {
        var neededSet = neededCats.ToHashSet();
        var toRemove = registry.Keys.Where(k => !neededSet.Contains(k)).ToList();

        foreach (var key in toRemove)
        {
            var btn = registry[key];
            parent.RemoveChild(btn);
            registry.Remove(key);
        }

        foreach (var cat in neededCats)
        {
            if (registry.ContainsKey(cat))
                continue;

            var btn = CreateCategoryButton(cat, onClick);
            registry[cat] = btn;
            parent.AddChild(btn);
        }

        foreach (var cat in neededCats)
        {
            if (!registry.TryGetValue(cat, out var btn))
                continue;

            parent.RemoveChild(btn);
            parent.AddChild(btn);
        }

        foreach (var (cat, btn) in registry)
        {
            var isSelected = cat == selectedCat;
            if (btn.Pressed != isSelected)
            {
                btn.Pressed = isSelected;
                btn.ModulateSelfOverride = isSelected ? CatSelected : CatIdle;
            }
        }
    }

    private string CurrencyName(string? currencyId)
    {
        if (string.IsNullOrWhiteSpace(currencyId))
            return string.Empty;

        if (_proto.TryIndex<StackPrototype>(currencyId, out var stackProto) &&
            _proto.TryIndex<EntityPrototype>(stackProto.Spawn, out var currencyEnt))
            return currencyEnt.Name;

        return currencyId;
    }

    private Color DifficultyColor(string diff, bool completed)
    {
        var baseColor = diff switch
        {
            "Easy" => Color.FromHex("#4CAF50"),
            "Medium" => Color.FromHex("#FFC107"),
            "Hard" => Color.FromHex("#F44336"),
            _ => Color.FromHex("#9E9E9E")
        };

        return completed ? Brighten(baseColor, 0.7f) : baseColor;
    }

    private string DifficultyName(string diff) =>
        diff switch
        {
            "Easy" => Loc.GetString("nc-store-difficulty-easy"),
            "Medium" => Loc.GetString("nc-store-difficulty-medium"),
            "Hard" => Loc.GetString("nc-store-difficulty-hard"),
            _ => diff
        };

    private static void UpdateCatVisuals(Dictionary<string, Button> map, string current)
    {
        foreach (var (name, btn) in map)
        {
            var selected = name == current;
            btn.Pressed = selected;
            btn.ModulateSelfOverride = selected ? CatSelected : CatIdle;
        }
    }

    private static Color Brighten(Color c, float f) =>
        new(MathF.Min(c.R * f, 1f), MathF.Min(c.G * f, 1f), MathF.Min(c.B * f, 1f), c.A);

    private void ResetPaging()
    {
        _pageBuy = 1;
        _pageSell = 1;
    }

