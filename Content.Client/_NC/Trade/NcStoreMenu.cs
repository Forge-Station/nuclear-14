    public void SetBalance(int balance)
    {
        _balance = balance;
        BalanceInfo.SetMarkup($"[font size=14][color=yellow]{balance}[/color][/font]");
    }

    private int GetBalanceForCurrency(string currencyId)
    {
        if (string.IsNullOrWhiteSpace(currencyId))
            return 0;

        return _balancesByCurrency.GetValueOrDefault(currencyId, 0);
    }

    private void UpdateBalanceHeader()
    {
        if (_balancesByCurrency.Count == 0)
        {
            SetBalance(0);
            return;
        }

        string? displayCurrency;
        int displayAmount;

        if (_balancesByCurrency.Count == 1)
        {
            var kv = _balancesByCurrency.First();
            displayCurrency = kv.Key;
            displayAmount = kv.Value;
        }
        else
        {
            string? bestKey = null;
            var bestValue = int.MinValue;

            foreach (var (key, value) in _balancesByCurrency)
                if (bestKey == null ||
                    value > bestValue ||
                    value == bestValue && string.CompareOrdinal(key, bestKey) < 0)
                {
                    bestKey = key;
                    bestValue = value;
                }

            displayCurrency = bestKey;
            displayAmount = _balancesByCurrency.Values.Sum();
        }

        BalanceInfo.SetMarkup($"[font size=14][color=yellow]{displayAmount}[/color][/font]");
        if (_currencyIcon != null && !string.IsNullOrEmpty(displayCurrency))
        {
            if (_proto.TryIndex<StackPrototype>(displayCurrency, out var stackProto) &&
                _proto.TryIndex<EntityPrototype>(stackProto.Spawn, out var entProto))
            {
                var icon = _sprites.GetPrototypeIcon(entProto).Default;
                _currencyIcon.Texture = icon;
            }
        }
    }

    public void SetBalancesByCurrency(Dictionary<string, int> balances)
    {
        _balancesByCurrency.Clear();

        foreach (var (cur, amt) in balances)
        {
            if (string.IsNullOrWhiteSpace(cur))
                continue;

            _balancesByCurrency[cur] = amt;
        }

        UpdateBalanceHeader();
    }


    public void SetMassSellTotals(Dictionary<string, int> totals)
    {
        _massSellTotals.Clear();
        foreach (var (cur, amt) in totals)
            _massSellTotals[cur] = amt;
        MassSellPulledCrateButton.Text = Loc.GetString("nc-store-mass-sell-button");
        MassSellPulledCrateButton.ClipText = true;

        if (_massSellTotals.Count == 0)
        {
            MassSellPulledCrateButton.ToolTip = Loc.GetString("nc-store-mass-sell-tooltip");
            MassSellPulledCrateButton.Disabled = true;
            return;
        }

        MassSellPulledCrateButton.Disabled = false;

        var parts = _massSellTotals
            .Where(p => p.Value > 0 && !string.IsNullOrWhiteSpace(p.Key))
            .Select(p => Loc.GetString(
                "nc-store-currency-format",
                ("amount", p.Value),
                ("currency", CurrencyName(p.Key))))
            .ToList();

        var full = parts.Count > 0 ? string.Join(", ", parts) : "—";

        MassSellPulledCrateButton.ToolTip = Loc.GetString("nc-store-mass-sell-tooltip-with-reward", ("reward", full));
    }

    private void CaptureTabsIfNeeded()
    {
        if (_tabsCaptured)
            return;

        _tabsCaptured = true;

        _tabBuy = TabBuy;
        _tabSell = TabSell;
        _tabContracts = TabContracts;
    }


    private void EnsureTab(Control? tab, bool shouldExist)
    {
        if (Tabs == null || tab == null)
            return;

        var exists = Tabs.Children.Contains(tab);

        if (shouldExist && !exists)
            Tabs.AddChild(tab);
        else if (!shouldExist && exists)
            Tabs.RemoveChild(tab);
    }


    private void ApplyTabsVisibility()
    {
        if (Tabs == null)
            return;

        CaptureTabsIfNeeded();

        EnsureTab(_tabBuy, _hasBuyTab);
        EnsureTab(_tabSell, _hasSellTab);
        EnsureTab(_tabContracts, _hasContractsTab);

        var count = Tabs.ChildCount;
        if (count <= 0)
            return;

        var curIndex = Tabs.CurrentTab;
        if (curIndex < 0 || curIndex >= count)
            Tabs.CurrentTab = 0;
    }


    public void PopulateCatalog(
        List<StoreListingStaticData> listings,
        bool hasBuyTab,
        bool hasSellTab,
        bool hasContractsTab
    )
    {
        _hasBuyTab = hasBuyTab;
        _hasSellTab = hasSellTab;
        _hasContractsTab = hasContractsTab;

        ApplyTabsVisibility();
        UpdateHeaderVisibility();

        _catalog.Clear();
        _staticById.Clear();

        foreach (var s in listings)
        {
            if (string.IsNullOrWhiteSpace(s.Id) || string.IsNullOrWhiteSpace(s.ProductEntity))
                continue;

            _catalog.Add(s);
            _staticById[s.Id] = s;
        }

        RebuildSearchIndexFromCatalog();
        RebuildCategoriesFromCatalog();

        ResetPaging();
        RefreshListings();
    }

    private void UpdateHeaderVisibility()
    {
        if (_headerBar == null)
            return;
        _headerBar.Visible = _hasBuyTab || _hasSellTab;
    }

    private void RebuildSearchIndexFromCatalog()
    {
        _searchIndex.Clear();
        foreach (var protoId in _catalog.Select(x => x.ProductEntity).Distinct())
            AddToSearchIndex(protoId);
    }

    private void RebuildCategoriesFromCatalog()
    {
        _buyCats.Clear();
        _sellCats.Clear();

        _buyCats.AddRange(
            _catalog.Where(i => i.Mode == StoreMode.Buy).Select(i => i.Category).Distinct().OrderBy(c => c));
        _sellCats.AddRange(
            _catalog.Where(i => i.Mode == StoreMode.Sell).Select(i => i.Category).Distinct().OrderBy(c => c));
        if (!_buyCats.Contains(_buyCat))
            _buyCat = string.Empty;
        if (!_sellCats.Contains(_sellCat))
            _sellCat = string.Empty;

        BuildCategoryButtons();
    }

    private void UpdateVirtualSellCategories()
    {
        var hasReady = _items.Any(i => i is { Mode: StoreMode.Sell, Category: CatIdReady, });
        var hasCrate = _items.Any(i => i is { Mode: StoreMode.Sell, Category: CatIdCrate, });

        _sellCats.Remove(CatIdReady);
        _sellCats.Remove(CatIdCrate);

        var insertIndex = 0;
        if (hasReady)
            _sellCats.Insert(insertIndex++, CatIdReady);

        if (hasCrate)
            _sellCats.Insert(insertIndex, CatIdCrate);

        if (!_sellCats.Contains(_sellCat))
            _sellCat = string.Empty;

        BuildCategoryButtons();
    }

    public void ApplyDynamicState(
        Dictionary<string, int> balancesByCurrency,
        Dictionary<string, int> remainingById,
        Dictionary<string, int> ownedById,
        Dictionary<string, int> crateUnitsById,
        Dictionary<string, int> massTotals,
        bool hasBuyTab,
        bool hasSellTab,
        bool hasContractsTab,
        List<ContractClientData> contracts
    )
    {
        _hasBuyTab = hasBuyTab;
        _hasSellTab = hasSellTab;
        _hasContractsTab = hasContractsTab;
        ApplyTabsVisibility();
        UpdateHeaderVisibility();

        SetBalancesByCurrency(balancesByCurrency);

        _remainingById.Clear();
        foreach (var (k, v) in remainingById)
            _remainingById[k] = v;

        _ownedById.Clear();
        foreach (var (k, v) in ownedById)
            _ownedById[k] = v;

        _crateUnitsById.Clear();
        foreach (var (k, v) in crateUnitsById)
            _crateUnitsById[k] = v;

        SetMassSellTotals(massTotals);
        PopulateContracts(contracts);

        RebuildItemsFromCatalogAndDynamic();
        UpdateVirtualSellCategories();
        RefreshListings();
    }

    private void RebuildItemsFromCatalogAndDynamic()
    {
        _items.Clear();

        foreach (var s in _catalog)
        {
            var remaining = _remainingById.GetValueOrDefault(s.Id, -1);
            var owned = _ownedById.GetValueOrDefault(s.Id, 0);

            _items.Add(
                new(
                    s.Id,
                    s.ProductEntity,
                    s.BasePrice,
                    s.Category,
                    s.CurrencyId,
                    s.Mode,
                    owned,
                    remaining));
        }

        var ready = _items
            .Where(d => d is { Mode: StoreMode.Sell, Owned: > 0, } && d.Remaining != 0)
            .Select(d => new StoreListingData(
                d.Id + "__ready",
                d.ProductEntity,
                d.Price,
                CatIdReady,
                d.CurrencyId,
                d.Mode,
                d.Owned,
                d.Remaining))
            .ToList();

        if (ready.Count > 0)
            _items.AddRange(ready);

        if (_crateUnitsById.Count > 0)
        {
            foreach (var s in _catalog.Where(x => x.Mode == StoreMode.Sell))
            {
                if (!_crateUnitsById.TryGetValue(s.Id, out var take) || take <= 0)
                    continue;

                var remaining = _remainingById.GetValueOrDefault(s.Id, 0);

                _items.Add(
                    new(
                        s.Id + "__crate",
                        s.ProductEntity,
                        s.BasePrice,
                        CatIdCrate,
                        s.CurrencyId,
                        StoreMode.Sell,
                        take,
                        remaining));
            }
        }

        var ids = _items.Select(i => i.Id).ToHashSet();
        foreach (var key in _qtyCache.Keys.Where(k => !ids.Contains(k)).ToList())
            _qtyCache.Remove(key);

        foreach (var key in _buyCache.Keys.Where(k => !ids.Contains(k)).ToList())
            _buyCache.Remove(key);

        foreach (var key in _sellCache.Keys.Where(k => !ids.Contains(k)).ToList())
            _sellCache.Remove(key);
    }


    public void Populate(List<StoreListingData> list)
    {
        _items.Clear();
        _items.AddRange(list);

        RebuildSearchIndex();

        var ids = _items.Select(i => i.Id).ToHashSet();
        foreach (var key in _qtyCache.Keys.Where(k => !ids.Contains(k)).ToList())
            _qtyCache.Remove(key);

        foreach (var key in _buyCache.Keys.Where(k => !ids.Contains(k)).ToList())
            _buyCache.Remove(key);
        foreach (var key in _sellCache.Keys.Where(k => !ids.Contains(k)).ToList())
            _sellCache.Remove(key);

        _buyCats.Clear();
        _sellCats.Clear();

        _buyCats.AddRange(
            list.Where(i => i.Mode == StoreMode.Buy)
                .Select(i => i.Category)
                .Distinct()
                .OrderBy(c => c));

        _sellCats.AddRange(
            list.Where(i => i.Mode == StoreMode.Sell)
                .Select(i => i.Category)
                .Distinct()
                .OrderBy(c => c));
        if (_items.Any(i => i is { Mode: StoreMode.Sell, Category: CatIdReady, }))
        {
            _sellCats.Remove(CatIdReady);
            _sellCats.Insert(0, CatIdReady);
        }

        if (!_buyCats.Contains(_buyCat))
            _buyCat = string.Empty;
        if (!_sellCats.Contains(_sellCat))
            _sellCat = string.Empty;

        BuildCategoryButtons();
        ResetPaging();
        RefreshListings();
    }

    private void RebuildSearchIndex()
    {
        _searchIndex.Clear();
        foreach (var protoId in _items.Select(i => i.ProductEntity).Distinct())
            AddToSearchIndex(protoId);
    }

    public void PopulateContracts(List<ContractClientData>? list)
    {
        var contractList = ContractList;
        if (contractList == null)
            return;

        contractList.RemoveAllChildren();

        if (list == null || list.Count == 0)
        {
            contractList.AddChild(
                new Label
                {
                    Text = Loc.GetString("nc-store-contracts-empty"),
                    HorizontalAlignment = HAlignment.Center,
                    Margin = new(0, 8, 0, 0)
                });

            ApplyTabsVisibility();
            return;
        }

        var ordered = list
            .OrderBy(x => x.Difficulty switch
            {
                "Easy" => 0,
                "Medium" => 1,
                "Hard" => 2,
                _ => 99
            })
            .ThenBy(x => x.Name)
            .ThenBy(x => x.Id)
            .ToList();

        foreach (var c in ordered)
        {
            var card = new NcContractCard(c, _proto, _sprites);
            card.OnClaim += id => OnContractClaim?.Invoke(id);
            contractList.AddChild(card);
        }

        ApplyTabsVisibility();
    }

    private void RefreshListings()
    {
        var hasSearch = !string.IsNullOrWhiteSpace(_search);
        var buyFiltered = Filtered(StoreMode.Buy, _buyCat).ToList();
        var sellFiltered = Filtered(StoreMode.Sell, _sellCat).ToList();

        var buyCount = buyFiltered.Count;
        var sellCount = sellFiltered.Count;

        BuyCategoryHeader.Visible = !string.IsNullOrEmpty(_buyCat) || hasSearch;
        SellCategoryHeader.Visible = !string.IsNullOrEmpty(_sellCat) || hasSearch;

        if (BuyCategoryHeader.Visible)
        {
            BuyCategoryHeader.Text = !string.IsNullOrEmpty(_buyCat)
                ? GetCategoryDisplayName(_buyCat)
                : Loc.GetString("nc-store-search-results-buy", ("count", buyCount));
        }
        else
            BuyCategoryHeader.Text = string.Empty;

        if (SellCategoryHeader.Visible)
        {
            SellCategoryHeader.Text = !string.IsNullOrEmpty(_sellCat)
                ? GetCategoryDisplayName(_sellCat)
                : Loc.GetString("nc-store-search-results-sell", ("count", sellCount));
        }
        else
            SellCategoryHeader.Text = string.Empty;

        var buyEmit = new Action<StoreListingData, int>((d, qty) => OnBuyPressed?.Invoke(d, qty));
        if (!TryUpdatePaneInPlace(BuyListingsContainer, StoreMode.Buy, _buyCat, buyFiltered, buyEmit))
        {
            FillPaneFull(
                BuyListingsContainer,
                StoreMode.Buy,
                _buyCat,
                buyFiltered,
                buyEmit);
        }

        var sellEmit = new Action<StoreListingData, int>((d, qty) => OnSellPressed?.Invoke(d, qty));
        if (!TryUpdatePaneInPlace(SellListingsContainer, StoreMode.Sell, _sellCat, sellFiltered, sellEmit))
        {
            FillPaneFull(
                SellListingsContainer,
                StoreMode.Sell,
                _sellCat,
                sellFiltered,
                sellEmit);
        }
    }

    private bool TryUpdatePaneInPlace(
        Control pane,
        StoreMode mode,
        string cat,
        List<StoreListingData> filtered,
        Action<StoreListingData, int> emit
    )
    {
        if (pane.Children.Any(c => c is Label))
            return false;

        var page = mode == StoreMode.Buy ? _pageBuy : _pageSell;
        var take = Math.Min(filtered.Count, PageSize * page);

        if (take <= 0)
            return false;

        var ctrls = pane.Children.OfType<NcStoreListingControl>().ToArray();

        if (ctrls.Length != take)
            return false;

        for (var i = 0; i < take; i++)
        {
            var it = filtered[i];
            var ctrl = ctrls[i];

            if (!string.Equals(ctrl.ListingId, it.Id, StringComparison.Ordinal))
                ctrl.UpdateIdentity(it);

            var balanceHint = mode == StoreMode.Buy
                ? GetBalanceForCurrency(it.CurrencyId)
                : int.MaxValue;

            var captured = it;
            ctrl.OnBuyPressed = mode == StoreMode.Buy ? qty => emit(captured, qty) : null;
            ctrl.OnSellPressed = mode == StoreMode.Sell ? qty => emit(captured, qty) : null;

            ctrl.UpdateDynamicData(balanceHint, it.Remaining, it.Owned);
        }

        RemoveMoreButtons(pane);
        AddOrUpdateMoreButton(pane, mode, filtered.Count, take, cat, emit);

        return true;
    }


    private IEnumerable<StoreListingData> Filtered(StoreMode mode, string cat)
    {
        var q = _items.Where(i => i.Mode == mode);

        var hasCat = !string.IsNullOrEmpty(cat);
        var hasSearch = !string.IsNullOrWhiteSpace(_searchLower);

        if (!hasCat && !hasSearch)
            return [];

        if (hasCat)
            q = q.Where(i => i.Category == cat);

        if (hasSearch)
            q = q.Where(i => MatchesSearch(i.ProductEntity));

        return q;
    }

    private void FillPaneFull(
        Control pane,
        StoreMode mode,
        string cat,
        List<StoreListingData> filtered,
        Action<StoreListingData, int> emit
    )
    {
        pane.Children.Clear();

        var hasCat = !string.IsNullOrEmpty(cat);
        var hasSearch = !string.IsNullOrWhiteSpace(_searchLower);

        if (!hasCat && !hasSearch)
        {
            pane.AddChild(new Label { Text = Loc.GetString("nc-store-select-category"), });
            return;
        }

        if (filtered.Count == 0)
        {
            var message = Loc.GetString(
                !string.IsNullOrEmpty(cat) ? "nc-store-empty-category-search" : "nc-store-empty-search");

            pane.AddChild(new Label { Text = message, });
            return;
        }

        var page = mode == StoreMode.Buy ? _pageBuy : _pageSell;
        var take = Math.Min(filtered.Count, PageSize * page);

        AddListingRange(pane, mode, filtered, 0, take, emit);

        AddOrUpdateMoreButton(pane, mode, filtered.Count, take, cat, emit);
    }


    private void AppendNextPage(Control pane, StoreMode mode, string cat, Action<StoreListingData, int> emit)
    {
        var filtered = Filtered(mode, cat).ToList();
        var page = mode == StoreMode.Buy ? _pageBuy : _pageSell;
        var take = Math.Min(filtered.Count, PageSize * page);

        var already = 0;
        foreach (var ch in pane.Children)
            if (ch is NcStoreListingControl)
                already++;

        var toAddStart = already;
        var toAddEnd = Math.Min(take, filtered.Count);

        if (toAddStart < toAddEnd)
            AddListingRange(pane, mode, filtered, toAddStart, toAddEnd, emit);

        RemoveMoreButtons(pane);
        AddOrUpdateMoreButton(pane, mode, filtered.Count, take, cat, emit);
    }

    private void AddListingRange(
        Control pane,
        StoreMode mode,
        List<StoreListingData> source,
        int startExclusive,
        int endExclusive,
        Action<StoreListingData, int> emit
    )
    {
        var cache = mode == StoreMode.Buy ? _buyCache : _sellCache;

        for (var i = startExclusive; i < endExclusive; i++)
        {
            var it = source[i];

            var balanceHint = mode == StoreMode.Buy
                ? GetBalanceForCurrency(it.CurrencyId)
                : int.MaxValue;

            var sig = Sig(it);

            if (!cache.TryGetValue(it.Id, out var tuple) || tuple.Sig != sig)
            {
                var initQty = _qtyCache.GetValueOrDefault(it.Id, 1);
                var actionsEnabled = true;

                var created = new NcStoreListingControl(it, _sprites, balanceHint, initQty, actionsEnabled);
                created.OnQtyChanged = newQty => _qtyCache[it.Id] = newQty;

                cache[it.Id] = (created, sig);
                tuple = (created, sig);
            }

            var ctrl = tuple.Ctrl;
            ctrl.OnBuyPressed = mode == StoreMode.Buy ? qty => emit(it, qty) : null;
            ctrl.OnSellPressed = mode == StoreMode.Sell ? qty => emit(it, qty) : null;

            ctrl.UpdateDynamicData(balanceHint, it.Remaining, it.Owned);

            pane.AddChild(ctrl);

            if (i < endExclusive - 1)
            {
                pane.AddChild(
                    new PanelContainer
                    {
                        MinSize = new Vector2i(0, 1),
                        StyleClasses = { "LowDivider", }
                    });
            }
        }
    }


    private static void RemoveMoreButtons(Control pane)
    {
        foreach (var ch in pane.Children.ToList())
        {
            if (ch is not Button b)
                continue;

            if (b.Name == "MoreButton")
                pane.RemoveChild(b);
        }
    }

    private void AddOrUpdateMoreButton(
        Control pane,
        StoreMode mode,
        int totalCount,
        int shown,
        string cat,
        Action<StoreListingData, int> emit
    )
    {
        if (shown >= totalCount)
            return;

        var left = totalCount - shown;

        var more = new Button
        {
            Name = "MoreButton",
            Text = Loc.GetString("nc-store-show-more", ("count", left)),
            HorizontalExpand = true,
            Margin = new(0, 8, 0, 8)
        };

        more.OnPressed += _ =>
        {
            if (mode == StoreMode.Buy)
                _pageBuy++;
            else
                _pageSell++;

            AppendNextPage(pane, mode, cat, emit);
        };

        pane.AddChild(more);
    }

    private void BuildCategoryButtons()
    {
        SyncCategoryButtons(
            _buyCats,
            BuyCategoryListContainer,
            _buyCatButtons,
            _buyCat,
            cat =>
            {
                _buyCat = _buyCat == cat ? string.Empty : cat;
                UpdateCatVisuals(_buyCatButtons, _buyCat);

                ResetPaging();
                RefreshListings();
            });

        SyncCategoryButtons(
            _sellCats,
            SellCategoryListContainer,
            _sellCatButtons,
            _sellCat,
            cat =>
            {
                _sellCat = _sellCat == cat ? string.Empty : cat;

                UpdateCatVisuals(_sellCatButtons, _sellCat);

                ResetPaging();
                RefreshListings();
            });
    }


    private void UpdateCatVisuals(Dictionary<string, Button> registry, string selectedCat)
    {
        foreach (var (cat, btn) in registry)
        {
            var isSelected = !string.IsNullOrEmpty(selectedCat) && cat == selectedCat;

            if (btn.Pressed != isSelected)
                btn.Pressed = isSelected;

            btn.ModulateSelfOverride = isSelected ? CatSelected : CatIdle;
        }
    }

    private Button CreateCategoryButton(string catId, Action<string> onClick)
    {
        var btn = new Button
        {
            Text = GetCategoryDisplayName(catId),
            ToggleMode = true,
            HorizontalExpand = true,
            ToolTip = GetCategoryToolTip(catId),
            ModulateSelfOverride = CatIdle
        };

        btn.OnPressed += _ => onClick(catId);
        btn.OnMouseEntered += _ =>
        {
            btn.ModulateSelfOverride = btn.Pressed
                ? Brighten(CatSelected, 1.2f)
                : Brighten(CatIdle, 1.2f);
        };

        btn.OnMouseExited += _ => { btn.ModulateSelfOverride = btn.Pressed ? CatSelected : CatIdle; };

        return btn;
    }

    private void SyncCategoryButtons(
        List<string> neededCats,
        Control parent,
        Dictionary<string, Button> registry,
        string selectedCat,
        Action<string> onClick
    )
    {
        var neededSet = neededCats.ToHashSet();
        var toRemove = registry.Keys.Where(k => !neededSet.Contains(k)).ToList();

        foreach (var key in toRemove)
        {
            var btn = registry[key];
            parent.RemoveChild(btn);
            registry.Remove(key);
        }

        foreach (var cat in neededCats)
        {
            if (registry.ContainsKey(cat))
                continue;

            var btn = CreateCategoryButton(cat, onClick);
            registry[cat] = btn;
            parent.AddChild(btn);
        }

        foreach (var cat in neededCats)
        {
            if (!registry.TryGetValue(cat, out var btn))
                continue;

            parent.RemoveChild(btn);
            parent.AddChild(btn);
        }

        foreach (var (cat, btn) in registry)
        {
            var isSelected = cat == selectedCat;
            if (btn.Pressed != isSelected)
            {
                btn.Pressed = isSelected;
                btn.ModulateSelfOverride = isSelected ? CatSelected : CatIdle;
            }
        }
    }

    private string CurrencyName(string? currencyId)
    {
        if (string.IsNullOrWhiteSpace(currencyId))
            return string.Empty;

        if (_proto.TryIndex<StackPrototype>(currencyId, out var stackProto) &&
            _proto.TryIndex<EntityPrototype>(stackProto.Spawn, out var currencyEnt))
            return currencyEnt.Name;

        return currencyId;
    }

    private static Color Brighten(Color c, float f) =>
        new(MathF.Min(c.R * f, 1f), MathF.Min(c.G * f, 1f), MathF.Min(c.B * f, 1f), c.A);

    private void ResetPaging()
    {
        _pageBuy = 1;
        _pageSell = 1;
    }

